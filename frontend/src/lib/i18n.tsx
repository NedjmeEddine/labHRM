export type TranslationKey = keyof typeof translations.fr
export type TranslateFn = (key: TranslationKey) => string

interface I18nContextValue {
  lang: Lang
  setLang: (lang: Lang) => void
  t: TranslateFn
}

const I18nContext = createContext<I18nContextValue | null>(null)

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = getStorageItem(STORAGE_KEYS.language)
    return saved === "en" || saved === "fr" ? saved : "fr"
  })

  const setLang = useCallback((next: Lang) => {
    setStorageItem(STORAGE_KEYS.language, next)
    setLangState(next)
  }, [])

  const t = useCallback<TranslateFn>(
    (key) => {
      return translations[lang][key] ?? translations.en[key] ?? key
    },
    [lang],
  )

  const value = useMemo<I18nContextValue>(
    () => ({ lang, setLang, t }),
    [lang, setLang, t],
  )

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

export function useTranslation() {
  const ctx = useContext(I18nContext)
  if (!ctx) {
    throw new Error("useTranslation must be used within I18nProvider")
  }
  return ctx
}

export function formatDZD(amount: number): string {
  return `${amount.toLocaleString("fr-DZ", { minimumFractionDigits: 2, maximumFractionDigits: 2 })} DZD`
}

